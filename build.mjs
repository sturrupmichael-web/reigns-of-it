// Builds index.html (the game) and validator.html (the card validator): each one a
// self-contained page with the CSS and all the game's JavaScript
// (including the card data) inlined, so each runs on any static host, at any path, and
// straight from disk. Edit the code under src/ and the content under data/, play it with
// dev.html, then run `npm run build`.

import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';

// Each page: its source HTML, the script and stylesheet it loads, and the built file.
const PAGES = [
  { src: 'dev.html', js: 'src/main.js', css: 'src/ui/style.css', out: 'index.html' },
  { src: 'validator-dev.html', js: 'src/tools/validator-page.js', css: 'src/tools/validator.css', out: 'validator.html' },
];

for (const page of PAGES) {
  const js = await build({
    entryPoints: [page.js],
    bundle: true,
    format: 'esm',
    target: 'es2022',
    minify: true,
    write: false,
    legalComments: 'none',
  });
  const css = await build({
    entryPoints: [page.css],
    bundle: true,
    minify: true,
    write: false,
  });

  const html = readFileSync(page.src, 'utf8')
    .replace(`<link rel="stylesheet" href="${page.css}">`, () => `<style>${css.outputFiles[0].text.trim()}</style>`)
    .replace(`<script type="module" src="${page.js}"></script>`, () =>
      `<script type="module">\n${js.outputFiles[0].text.replaceAll('</script', '<\\/script')}</script>`,
    )
    .replace('<title>', `<!-- Generated by build.mjs from ${page.src}, src/ and data/. Do not edit by hand. -->\n  <title>`);
  if (html.includes('src="src/') || html.includes('href="src/')) throw new Error(`${page.src} references a file the build did not inline`);

  writeFileSync(page.out, withCsp(html));
  console.log(`${page.out}: ${(html.length / 1024).toFixed(0)} KB`);
}

// Content Security Policy: the page may only run its own (inline, hashed) scripts and
// talks to nothing but its own site.
function withCsp(page) {
  const hashes = [...page.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
    (m) => `'sha256-${createHash('sha256').update(m[1]).digest('base64')}'`,
  );
  const csp = [
    "default-src 'self'",
    `script-src 'self' ${hashes.join(' ')}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');
  return page.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${csp}">`);
}
